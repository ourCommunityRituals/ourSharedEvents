#!/usr/bin/env node
/**
 * Build workers/oursharedevents/src/lib/zip-areas-data.ts: one line per US ZIP
 * Code Tabulation Area with its center point, sorted by zip, fixed width so
 * the Worker can look a zip up by binary search without parsing the list.
 *
 * Source: the US Census Bureau's ZCTA centers, as packaged by the npm package
 * us-zips@2022.9.1 (MIT, Blake Knight). Fetch and unpack it yourself, then
 * pass the path of its object.js. This script reads that file as TEXT with a
 * regular expression; it never runs it.
 *
 *   npm pack us-zips@2022.9.1 && tar xzf us-zips-2022.9.1.tgz
 *   node scripts/gen-zip-areas.mjs package/object.js
 *
 * Record: ZZZZZ±LL.LLL±LLL.LLL (20 characters) + "\n". Three decimals is
 * about 110 m, far finer than the ~2.4 km area cell it is turned into.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-zip-areas.mjs <path to us-zips object.js>');
  process.exit(2);
}
const text = readFileSync(src, 'utf8');
const RECORD =
  /^\s*"?(\d{5})"?:\s*\{latitude:\s*(-?\d+(?:\.\d+)?),\s*longitude:\s*(-?\d+(?:\.\d+)?)\}/gm;

const sign = (n, intDigits) => {
  const s = Math.abs(n)
    .toFixed(3)
    .padStart(intDigits + 4, '0');
  return (n < 0 ? '-' : '+') + s;
};

const rows = new Map();
for (const m of text.matchAll(RECORD)) {
  const lat = Number(m[2]);
  const lon = Number(m[3]);
  if (!(lat >= -90 && lat <= 90 && lon >= -180 && lon <= 180)) continue;
  rows.set(m[1], `${m[1]}${sign(lat, 2)}${sign(lon, 3)}`);
}
const lines = [...rows.keys()].sort().map((k) => rows.get(k));
if (lines.length < 30000) {
  console.error(`only ${lines.length} zips parsed; expected about 33,791`);
  process.exit(1);
}
for (const l of lines) if (l.length !== 20) throw new Error(`bad record ${l}`);

const out = join(
  import.meta.dirname,
  '..',
  'workers',
  'oursharedevents',
  'src',
  'lib',
  'zip-areas-data.ts'
);
writeFileSync(
  out,
  `/* eslint-disable */
// prettier-ignore
/**
 * US ZIP Code Tabulation Area centers (${lines.length} zips). Generated by
 * scripts/gen-zip-areas.mjs; do not edit by hand.
 *
 * Data: US Census Bureau ZCTA centers (public domain), packaged by us-zips
 * 2022.9.1, MIT License, Copyright (c) 2021 Blake Knight.
 *
 * One record per line, sorted by zip: ZZZZZ±LL.LLL±LLL.LLL (20 characters).
 */
export const ZIP_AREA_RECORD = 20;
export const ZIP_AREA_COUNT = ${lines.length};
export const ZIP_AREAS = \`
${lines.join('\n')}
\`;
`
);
console.log(`wrote ${lines.length} zips to ${out}`);
