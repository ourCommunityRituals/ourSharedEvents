#!/usr/bin/env node
/**
 * Build workers/oursharedevents/src/lib/place-names-data.ts: every US town or
 * city name with its state and its zips, so the landing page can search by name
 * first (owner 2026-11-06). One name can be many places ("Springfield" is in 24
 * states); each (name, state) is one line.
 *
 * Source: the GeoNames US postal code file (CC BY 4.0, www.geonames.org), the
 * owner's choice 2026-11-06. Download and unpack it yourself, then pass the
 * path of US.txt. This script reads that file as TEXT; it never runs it.
 *
 *   curl -O https://download.geonames.org/export/zip/US.zip && unzip US.zip
 *   node scripts/gen-place-names.mjs US.txt
 *
 * Record: Name|ST|zip zip zip (zips sorted). Lines are sorted by placeKey(Name),
 * then state, so the Worker finds a name by binary search. placeKey here MUST
 * match placeKey in src/lib/place-search.ts; a unit test checks the order with
 * the Worker's own function, so a drift fails CI.
 *
 * Spellings that mean the same place in one state ("Saint Louis", "St. Louis")
 * are one line, named by the spelling with the most zips.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/gen-place-names.mjs <path to GeoNames US.txt>');
  process.exit(2);
}

const WORDS = { saint: 'st', mount: 'mt', fort: 'ft' };
/** Keep in step with placeKey in src/lib/place-search.ts. */
function placeKey(s) {
  return s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[.']/g, '')
    .replace(/[\s-]+/g, ' ')
    .trim()
    .replace(/\b(saint|mount|fort)\b/g, (w) => WORDS[w]);
}

const STATE = /^[A-Z]{2}$/;
const ZIP = /^\d{5}$/;
// A name the data file can hold as is: no line break, field separator or
// template-literal character.
const SAFE_NAME = /^[^|\n\r`$\\]{1,60}$/;

/** key|ST → { names: Map<display name, zip count>, zips: Set } */
const groups = new Map();
for (const line of readFileSync(src, 'utf8').split('\n')) {
  const f = line.split('\t');
  if (f.length < 5 || f[0] !== 'US') continue;
  const zip = f[1];
  const name = f[2].trim();
  const st = f[4];
  if (!ZIP.test(zip) || !STATE.test(st) || !SAFE_NAME.test(name)) continue;
  const key = placeKey(name);
  if (!key) continue;
  const g = groups.get(`${key}|${st}`) ?? { key, st, names: new Map(), zips: new Set() };
  g.names.set(name, (g.names.get(name) ?? 0) + 1);
  g.zips.add(zip);
  groups.set(`${key}|${st}`, g);
}

const rows = [...groups.values()]
  .map((g) => {
    const name = [...g.names.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))[0][0];
    return { key: g.key, st: g.st, line: `${name}|${g.st}|${[...g.zips].sort().join(' ')}` };
  })
  .sort((a, b) =>
    a.key < b.key ? -1 : a.key > b.key ? 1 : a.st < b.st ? -1 : a.st > b.st ? 1 : 0
  );

if (rows.length < 25000) {
  console.error(`only ${rows.length} places parsed; expected about 29,000`);
  process.exit(1);
}

const out = join(
  import.meta.dirname,
  '..',
  'workers',
  'oursharedevents',
  'src',
  'lib',
  'place-names-data.ts'
);
writeFileSync(
  out,
  `/* eslint-disable */
// prettier-ignore
/**
 * US town and city names with their state and zips (${rows.length} places).
 * Generated by scripts/gen-place-names.mjs; do not edit by hand.
 *
 * Data: GeoNames postal codes (www.geonames.org), licensed under Creative
 * Commons Attribution 4.0 (https://creativecommons.org/licenses/by/4.0/).
 * The landing page credits GeoNames where the search box is.
 *
 * One record per line, sorted by placeKey(name) then state: Name|ST|zip zip zip.
 */
export const PLACE_NAME_COUNT = ${rows.length};
export const PLACE_NAMES = \`
${rows.map((r) => r.line).join('\n')}
\`;
`
);
console.log(`wrote ${rows.length} places to ${out}`);
