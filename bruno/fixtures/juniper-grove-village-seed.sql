--
-- A practice account shaped like a small village government and the public
-- bodies around it: village-wide events, a recreation department, a senior
-- and community services office, an outdoor field and rink, the public
-- library and the local schools. Same pattern as the Lakeside and Meadowlark
-- practice trees: stand-in names for practice on staging only; no real place
-- is named here. Which prospect it stands in for is kept off this repository.
--
--   juniper-village            the village itself (parade, festival, concerts, resale weekend)
--    ├── juniper-recreation    day camp, classes and adult leagues
--    ├── juniper-seniors       luncheons, a 55+ prom, day trips
--    ├── juniper-fields        the outdoor rink and field (skating, pickleball, fun run)
--    ├── juniper-library       storytime, teen gaming, book discussion
--    └── juniper-schools       school concerts and family nights
--
-- In real life the library and the schools are their own public bodies, not
-- departments of the village. They sit under the village here so one practice
-- sign-in shows the whole footprint. For a public body, the body decides what
-- happens to its data (ADR-023).
--
-- A member of juniper-village reaches all six brands (lib/brand-tree.ts); a
-- member of one child reaches only that child. Who is a member is the owner's
-- STAGING_TESTERS setting, never this file.
--
-- Events are practice data (data_class 'demo') and unpublished: off the
-- landing list and the attendee map. They sit in the CI fixture's area cell
-- and its two neighbours (res 7), so no real address is implied. No person,
-- no coordinates. Each event's picture is one of the owner's photographs in
-- stock/art, uploaded by the CI step to events/practice-art/ in the staging
-- uploads bucket.
--
-- Practice traffic: one poster per event and stand-in scans, so the village's
-- reports show every department, place and area cell. Two events stay under
-- 5 scans and must read "Fewer than 5". One anonymous row per scan; no
-- person, device or session. Never apply to production.
--
-- Applied by CI on staging only, after T1 has run the migrations:
--   node ../../scripts/ci/d1-seed-staging.mjs DB ../../bruno/fixtures/juniper-grove-village-seed.sql
