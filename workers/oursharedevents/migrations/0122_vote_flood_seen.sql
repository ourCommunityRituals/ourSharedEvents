-- Migration 0122: a vote set remembers that a flood of vote passes was seen
-- (OSE-2234; OSE ADR-040 decision 6, amended 2026-11-26: detection only).
--
-- One column on vote_sets:
--
--   flood_seen   0 or 1. It turns to 1, once, when `/q` mints more vote passes
--                for the event's vote code in one minute than a full room
--                would (src/lib/vote-flood.ts). Nothing sets it back to 0: not
--                a reopen, not final, not the nightly job. The gate
--                votes-never-who holds that it is set only to the literal 1.
--
-- It is a flag, not a count. It holds no time, no count, no address, no
-- cookie, no k and no pass. The minute it tripped is not kept in the
-- database: the write does not touch updated_at. (The one log line,
-- VOTE_FLOOD_SEEN with the event id, carries the log host's own time.) The count itself lives only in a Workers Rate Limiting
-- binding keyed by the event id, in memory, for one minute.
--
-- Who sees it: the host, in the admin Voting card, and, once the set is final,
-- the voter page's result says the result may be padded. Never the display,
-- display-config, or any public answer before final (AGENTS.md invariants 2
-- and 5).
--
-- Time: no new time column.
--
-- Gates: tests/e2e/0-architecture/votes-never-who.invariant.spec.ts (T0),
-- workers/oursharedevents/tests/vote-flood.spec.ts (workers pool).
--
-- Additive only: one column with a default. No row is written or rewritten.
--
-- Rollback: revert the Worker and leave the column. The older Worker reads
-- none of it. See ROLLBACK_PLAN.md, 0122.

ALTER TABLE vote_sets ADD COLUMN flood_seen INTEGER NOT NULL DEFAULT 0
  CHECK (flood_seen IN (0, 1));
