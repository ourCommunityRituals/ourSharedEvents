/**
 * OSE-628 | INT-01 + DESIGN — corridor_map SVG rendering gate
 *
 * Source-level gates asserting that shared-report.html correctly wires up
 * the corridor_map payload from the SharedReport API response:
 *
 *   1. Section is the AC-named container: id="corridor-map-container",
 *      data-testid="corridor-map-section", aria-labelledby="section-corridor-map"
 *   2. SVG is injected directly (report.corridor_map.svg — not escaped)
 *   3. Source distinction: 'fallback' → "Neighborhood Preview" heading,
 *      'live' → "Corridor Scan Map" heading
 *   4. Source note is rendered only for fallback maps
 *   5. Suppressed source ('suppressed') → suppression copy instead of the SVG
 *   6. cell_count rendered in a stat chip alongside the map
 *   7. Field-level suppression path: null corridor_map + suppression_reasons entry
 *   8. DESIGN: corridor_map section is mobile-first responsive (base = mobile,
 *      min-width enhancements for tablet + laptop) so it renders on phone,
 *      tablet, and laptop.
 */

import { env } from 'cloudflare:test';
import { describe, test, expect } from 'vitest';

interface TestEnv {
  TEST_SOURCE_FILES_JSON: string;
}

function getTemplate(): string {
  const sources: Record<string, string> = JSON.parse(
    (env as unknown as TestEnv).TEST_SOURCE_FILES_JSON
  );
  const entry = Object.entries(sources).find(([p]) =>
    p.replace(/\\/g, '/').endsWith('templates/shared-report.html')
  );
  if (!entry) throw new Error('shared-report.html not found in TEST_SOURCE_FILES_JSON');
  return entry[1];
}

describe('OSE-628 | INT-01 | corridor_map SVG render gate', () => {
  test('template renders the AC-named corridor-map-section container', () => {
    const src = getTemplate();
    expect(src).toContain('id="corridor-map-container"');
    expect(src).toContain('data-testid="corridor-map-section"');
    expect(src).toContain('aria-labelledby="section-corridor-map"');
    // The heading the section is labelled by must exist.
    expect(src).toContain('id="section-corridor-map"');
  });

  test('template injects corridor_map.svg directly (not escaped)', () => {
    const src = getTemplate();
    expect(src).toContain('cm.svg');
    // Ensure it is NOT passed through esc() — direct innerHTML injection is
    // correct because the SVG is generated by our own trusted renderCorridorMap().
    expect(src).not.toMatch(/esc\(\s*cm\.svg\s*\)/);
    expect(src).not.toMatch(/esc\(\s*report\.corridor_map\.svg\s*\)/);
  });

  test('template renders "Corridor Scan Map" heading for live source', () => {
    const src = getTemplate();
    expect(src).toContain('Corridor Scan Map');
  });

  test('template renders "Neighborhood Preview" heading for fallback source', () => {
    const src = getTemplate();
    expect(src).toContain('Neighborhood Preview');
  });

  test('template shows fallback source note only when source is fallback', () => {
    const src = getTemplate();
    expect(src).toContain('corridor-map-source-note');
    // Note is rendered only inside the fallback branch (source === 'fallback').
    expect(src).toMatch(/source === 'fallback'[\s\S]*?corridor-map-source-note/);
  });

  test('template shows suppression copy when source === suppressed (no SVG)', () => {
    const src = getTemplate();
    expect(src).toMatch(/source === 'suppressed'/);
    expect(src).toContain('corridor-map-suppressed-note');
  });

  test('template renders cell_count in a stat chip alongside the map', () => {
    const src = getTemplate();
    expect(src).toContain('corridor-map-cell-count');
    expect(src).toMatch(/fmtInt\(\s*cm\.cell_count\s*\)/);
  });

  test('template shows suppression note when corridor_map is null and field is suppressed', () => {
    const src = getTemplate();
    // When corridor_map is null, fall through to suppressionNote('corridor_map').
    expect(src).toMatch(/suppressionNote\(['"]corridor_map['"]\)/);
  });

  test('corridor_map section is mobile-first responsive (base + tablet + laptop)', () => {
    const src = getTemplate();
    // Base rule: the SVG fills its container on phones (width:100%).
    expect(src).toMatch(/\.corridor-map svg\s*\{[^}]*width:\s*100%/);
    // Tablet enhancement.
    expect(src).toMatch(/@media\s*\(\s*min-width:\s*700px\s*\)/);
    // Laptop enhancement.
    expect(src).toMatch(/@media\s*\(\s*min-width:\s*1024px\s*\)/);
  });
});
